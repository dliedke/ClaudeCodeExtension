using ClaudeCodeVS;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace ClaudeCodeExtension.Tests
{
    [TestClass]
    public class CommitMessageCleanupTests
    {
        [TestMethod]
        public void CoAuthoredByTrailerIsRemoved()
        {
            string cleaned = ClaudeCodeControl.CleanCommitMessage(
                "feat: add SubDL source\n\n- Separator in the log\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>");

            Assert.AreEqual("feat: add SubDL source\n\n- Separator in the log", cleaned);
        }

        [TestMethod]
        public void MarkdownWrappedAndLowercaseTrailersAreRemoved()
        {
            string cleaned = ClaudeCodeControl.CleanCommitMessage(
                "fix: retry\n\n**Co-Authored-By:** Claude <noreply@anthropic.com>\nco-authored-by: Codex <noreply@openai.com>");

            Assert.AreEqual("fix: retry", cleaned);
        }

        [TestMethod]
        public void GeneratedWithFooterIsRemoved()
        {
            string cleaned = ClaudeCodeControl.CleanCommitMessage(
                "fix: retry\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)");

            Assert.AreEqual("fix: retry", cleaned);
        }

        [TestMethod]
        public void HumanLinesMentioningGenerationAreKept()
        {
            const string message = "build: regenerate files\n\nGenerated by the T4 template on build.";

            Assert.AreEqual(message, ClaudeCodeControl.CleanCommitMessage(message));
        }

        [TestMethod]
        public void CodeFenceIsStrippedTogetherWithTheTrailer()
        {
            string cleaned = ClaudeCodeControl.CleanCommitMessage(
                "```\ndocs: update README\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n```");

            Assert.AreEqual("docs: update README", cleaned);
        }
    }
}
