using ClaudeCodeVS;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Newtonsoft.Json.Linq;

namespace ClaudeCodeExtension.Tests
{
    [TestClass]
    public class SessionTranscriptFilterTests
    {
        /// <summary>
        /// The shape Claude Code actually writes when a local command runs: an ordinary "user" line
        /// with real text, told apart from a typed prompt only by the isMeta flag.
        /// </summary>
        [TestMethod]
        public void IsMetaTranscriptLine_TrueForTheLocalCommandCaveat()
        {
            JObject line = JObject.Parse(
                @"{""type"":""user"",""isMeta"":true,""message"":{""content"":""<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>""}}");

            Assert.IsTrue(ClaudeCodeControl.IsMetaTranscriptLine(line));
        }

        [TestMethod]
        public void IsMetaTranscriptLine_FalseForARealPrompt()
        {
            JObject line = JObject.Parse(@"{""type"":""user"",""message"":{""content"":""fix the build""}}");

            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(line));
        }

        [TestMethod]
        public void IsMetaTranscriptLine_FalseForBooleanFalse()
        {
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(JObject.Parse(@"{""isMeta"":false}")));
        }

        /// <summary>
        /// Locks the exact contract: only the JSON boolean counts. This is what a plain
        /// <c>(bool?)obj["isMeta"] == true</c> gets wrong — Newtonsoft coerces the string "true" to
        /// true, which would start hiding real prompts if the CLI ever wrote that shape.
        /// </summary>
        [TestMethod]
        public void IsMetaTranscriptLine_FalseForTheStringTrue()
        {
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(JObject.Parse(@"{""isMeta"":""true""}")));
        }

        /// <summary>
        /// Same cast would throw <c>FormatException</c> here, taking the whole transcript read with it.
        /// </summary>
        [TestMethod]
        public void IsMetaTranscriptLine_DoesNotThrowOnAValueThatIsNotABoolean()
        {
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(JObject.Parse(@"{""isMeta"":""yes""}")));
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(JObject.Parse(@"{""isMeta"":null}")));
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(JObject.Parse(@"{""isMeta"":1}")));
        }

        [TestMethod]
        public void IsMetaTranscriptLine_FalseForNull()
        {
            Assert.IsFalse(ClaudeCodeControl.IsMetaTranscriptLine(null));
        }

        /// <summary>
        /// The shape a typed slash command (e.g. "/effort medium") is expanded into by the CLI —
        /// not isMeta-flagged, so IsMetaTranscriptLine alone would let it through as a real prompt.
        /// </summary>
        [TestMethod]
        public void IsCommandInvocationText_TrueForACommandBlock()
        {
            string text = "<command-name>/effort</command-name>\n" +
                "            <command-message>effort</command-message>\n" +
                "            <command-args>medium</command-args>";

            Assert.IsTrue(ClaudeCodeControl.IsCommandInvocationText(text));
        }

        [TestMethod]
        public void IsCommandInvocationText_FalseForARealPrompt()
        {
            Assert.IsFalse(ClaudeCodeControl.IsCommandInvocationText("fix the build"));
        }

        [TestMethod]
        public void IsCommandInvocationText_FalseForEmptyOrNull()
        {
            Assert.IsFalse(ClaudeCodeControl.IsCommandInvocationText(string.Empty));
            Assert.IsFalse(ClaudeCodeControl.IsCommandInvocationText(null));
        }

        [TestMethod]
        public void IsCommandInvocationText_TrueWithLeadingWhitespace()
        {
            Assert.IsTrue(ClaudeCodeControl.IsCommandInvocationText("  \n<command-name>/effort</command-name>"));
        }

        /// <summary>
        /// The name the exported transcript's Title line is resolved from: the rename the user
        /// gave the session, falling back to the first prompt when there is none.
        /// </summary>
        [TestMethod]
        public void DisplayTitle_PrefersTheCustomTitle()
        {
            var session = new SessionInfo { CustomTitle = "Fix terminal focus on WSL", Preview = "why is the terminal blank" };

            Assert.AreEqual("Fix terminal focus on WSL", session.DisplayTitle);
        }

        [TestMethod]
        public void DisplayTitle_FallsBackToThePreviewWhenNotRenamed()
        {
            Assert.AreEqual("why is the terminal blank",
                new SessionInfo { CustomTitle = string.Empty, Preview = "why is the terminal blank" }.DisplayTitle);
            Assert.AreEqual("why is the terminal blank",
                new SessionInfo { CustomTitle = "   ", Preview = "why is the terminal blank" }.DisplayTitle);
        }

        /// <summary>
        /// A custom title pasted from a multi-line selection must not split the one-line header.
        /// </summary>
        [TestMethod]
        public void NormalizeTranscriptTitle_FlattensNewlinesAndTabs()
        {
            Assert.AreEqual("fix the build then ship it",
                ClaudeCodeControl.NormalizeTranscriptTitle("  fix the\r\nbuild\tthen   ship it  "));
        }

        [TestMethod]
        public void NormalizeTranscriptTitle_CapsOverLongTitles()
        {
            string result = ClaudeCodeControl.NormalizeTranscriptTitle(new string('a', 200));

            Assert.AreEqual(new string('a', 120) + "…", result);
        }

        [TestMethod]
        public void NormalizeTranscriptTitle_KeepsATitleAtTheCapIntact()
        {
            string exact = new string('a', 120);

            Assert.AreEqual(exact, ClaudeCodeControl.NormalizeTranscriptTitle(exact));
        }

        [TestMethod]
        public void NormalizeTranscriptTitle_PlaceholderForBlankInput()
        {
            Assert.AreEqual("(untitled session)", ClaudeCodeControl.NormalizeTranscriptTitle(null));
            Assert.AreEqual("(untitled session)", ClaudeCodeControl.NormalizeTranscriptTitle("   "));
        }
    }
}
